const {chromium}=await import(process.env.PLAYWRIGHT_MODULE_PATH || 'playwright');
import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
import http from 'node:http';
const html=await fs.readFile(new URL('../app/src/main/assets/index.html',import.meta.url));
const server=http.createServer((req,res)=>{res.setHeader('Content-Type','text/html');res.end(html)});
await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
const testURL=`http://127.0.0.1:${server.address().port}/`;
const browser=await chromium.launch({headless:true,executablePath:process.env.BROWSER_EXECUTABLE || undefined,args:['--no-sandbox']});
const results=[];
for(const size of [{width:320,height:568},{width:360,height:640},{width:412,height:820}]){
 const context=await browser.newContext({viewport:size});
 await context.addInitScript(()=>{localStorage.setItem('parkingEscape150Stable',JSON.stringify({unlocked:40,stars:[3,2],coins:777,lang:'cs',sound:false,vib:false,skin:'yellow',owned:['yellow']})); window.adCalls=0; window.AndroidAds={showRewardedAd(){window.adCalls++},showInterstitialAd(){window.adCalls++}}});
 const page=await context.newPage();const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto(testURL);
 assert.equal(await page.locator('#coins').innerText(),'777');
 assert.equal(await page.locator('#progress').innerText(),'40/150');
 await page.locator('#levelsBtn').click();assert.equal(await page.locator('#levelGrid button').count(),150);
 assert.equal(await page.locator('#levelGrid button:disabled').count(),110);
 await page.locator('#levelGrid button').nth(0).click();
 assert.equal(await page.locator('#levelNo').innerText(),'1');
 const car=await page.locator('#board [data-id="Y"] .car').boundingBox();
 await page.mouse.move(car.x+car.width/2,car.y+car.height/2);await page.mouse.down();await page.mouse.move(car.x+car.width,car.y+car.height/2,{steps:5});await page.mouse.up();
 assert.equal(await page.locator('#moves').innerText(),'1');
 await page.locator('#undo').click();assert.equal(await page.locator('#moves').innerText(),'0');
 await page.locator('#hint').click();assert.equal(await page.evaluate(()=>window.adCalls),1);
 await page.evaluate(()=>window.onRewardedAdUnavailable());assert.match(await page.locator('#msg').innerText(),/připravena/);
 await page.locator('#hint').click();assert.equal(await page.evaluate(()=>window.adCalls),2);
 await page.evaluate(()=>window.onRewardedAdEarned());assert.match(await page.locator('#msg').innerText(),/💡/);
 await page.locator('#restart').click();assert.equal(await page.locator('#moves').innerText(),'0');
 const board=await page.locator('#board').boundingBox();const cell=board.width*88/650;
 const lower=await page.locator('#board [data-id="C"] .car').boundingBox();
 await page.mouse.move(lower.x+lower.width/2,lower.y+lower.height/2);await page.mouse.down();await page.mouse.move(lower.x+lower.width/2-2*cell,lower.y+lower.height/2,{steps:12});await page.mouse.up();
 const blocker=await page.locator('#board [data-id="A"] .car').boundingBox();
 await page.mouse.move(blocker.x+blocker.width/2,blocker.y+blocker.height/2);await page.mouse.down();await page.mouse.move(blocker.x+blocker.width/2,blocker.y+blocker.height/2+2*cell,{steps:12});await page.mouse.up();
 const target=await page.locator('#board [data-id="Y"] .car').boundingBox();
 await page.mouse.move(target.x+target.width/2,target.y+target.height/2);await page.mouse.down();await page.mouse.move(target.x+target.width/2+4*cell,target.y+target.height/2,{steps:24});await page.mouse.up();
 await page.locator('#win').waitFor({state:'visible',timeout:5000});
 await page.locator('#win [data-home]').click();assert.equal(await page.locator('#coins').innerText(),'782');
 await page.locator('#dailyBtn').click();await page.locator('#playDaily').click();await page.locator('#board').waitFor({state:'visible'});await page.locator('#back').click();
 await page.locator('#garageBtn').click();assert.equal(await page.locator('#garageCoins').innerText(),'782');
 assert.deepEqual(errors,[]);results.push({viewport:size,levels:150,progressPreserved:true,dragUndoRestart:true,normalWinReward:true,dailyStart:true,rewardBridgeStub:true,pageErrors:errors});await context.close();
}
await browser.close();server.close();await fs.mkdir(new URL('../qa',import.meta.url),{recursive:true});await fs.writeFile(new URL('../qa/browser-smoke.json',import.meta.url),JSON.stringify(results,null,2));console.log(JSON.stringify(results));
